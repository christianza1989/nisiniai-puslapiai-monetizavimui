function label(field,code,text){
 text=(text||'').replace(/\u00a0/g,' ').trim();
 if(field.startsWith('CPRICEGROUP'))return 'Grupė '+code.replace(/^_/,'');
 if(field==='CARMRESTS'){
  if(code==='NONE')return 'Be porankių';
  const dimensions=text.match(/\b(?:[1-4]D|X-D)\b/i)?.[0];if(dimensions)return code+' · '+dimensions;
  if(/fixed/i.test(text))return code+' · fiksuoti';
 }
 if(/^\d+(?:[.,]\d+)?\s*(?:mm|cm|m|kg|°)$/.test(text))return text;
 if(terms.has(text))return terms.get(text);
 if(field==='CGLIDES'){
  if(text==='Plastic with felt')return code+' · plastikinės, su veltiniu';
  const name=text.split(':')[0];
  if(/for soft or hard floors, acoustic/i.test(text))return name+' · akustinės, įvairioms grindims';
  if(/for hard floors, with felt/i.test(text))return name+' · kietoms grindims, su veltiniu';
  if(/for hard floors/i.test(text))return name+' · kietoms grindims';
  if(/for soft floors/i.test(text))return name+' · minkštoms grindims';
 }
 if(field==='CASSEMBLY'&&/Fully assembled, collective packaging/i.test(text))return code+' · visiškai surinkta, grupinė pakuotė';
 if(field==='CCONNECTOR'&&code!=='NONE')return code+' · jungtis kėdžių eilėms';
 if(field==='CTABLET'){
  if(/left hand/i.test(text))return code+' · kairėje pusėje';
  if(/right hand/i.test(text))return code+' · dešinėje pusėje';
 }
 return code;
}
export function localizeAdditionalPalettes(palettes,anchors,existingLabels){
 const fields=new Set(anchors.flatMap(a=>[...Object.keys(a.choices),...a.axes,...a.components.flatMap(c=>[...c.fields,...c.variants.flatMap(v=>Object.keys(v.dependentChoices||{}))]),...a.profiles.flatMap(p=>Object.keys(p.choices))]));
 const missing=[...fields].filter(k=>!additionalFieldLabels[k]&&!existingLabels[k]);
 palettes._fieldLabels=Object.fromEntries([...fields].filter(k=>additionalFieldLabels[k]).map(k=>[k,{text:additionalFieldLabels[k]}]));
 palettes._valueLabels={};
 for(const field of fields){
  if(!additionalFieldLabels[field]&&field!=='CARMRESTS')continue;
  for(const [code,entry] of Object.entries(palettes[field]||{}))palettes._valueLabels[field+'='+code]={text:label(field,code,entry.text)};
 }
 return missing;
}
