function carouselModule(filename,name){
  let code=fs.readFileSync(path.join(source,filename),'utf8').trim();
  code=code.replace(/^\(\(\) => \{\s*/,`export function ${name}(root) {\n`).replace(/\}\)\(\);$/,'');
  code=code.replace('document.querySelector(', 'root.querySelector(');
  // Namespace selectors, not textual labels or product routes.
  code=code.replace(/\.((?:category|carousel|guide)-[\w-]+)/g,'.hp-$1');
  code=code.replace(/\b(\w+)\.addEventListener\(/g,'listen($1, ');
  code=code.replaceAll('new IntersectionObserver(', 'watchIntersection(').replaceAll('new ResizeObserver(', 'watchResize(');
  // The owner explicitly requested autoplay on both rails. The browser's
  // reduced-motion flag still controls manual scroll transitions, but must
  // neither silently disable this chosen behavior nor block the Play button.
  code=code.replace(/function canRun\(\) \{\s*return /,'function canRun() { return !destroyed && ');
  if(name==='mountGuides'){
    code=code.replace('let paused = reducedMotion.matches;','let paused = false;');
    code=code.replace("listen(reducedMotion, 'change', () => {\n    paused = reducedMotion.matches;\n    setPlayState();\n    sync();\n  });","listen(reducedMotion, 'change', sync);");
  }
  code=code.replace(/function sync\(\) \{/, 'function sync() { if (destroyed) return;');
  const setup=`let destroyed=false;const lifecycle=new AbortController(),observers=[];
function listen(target,type,callback,options={}) { target.addEventListener(type,callback,{...options,signal:lifecycle.signal}); }
function watchIntersection(callback,options) { const observer=new IntersectionObserver(callback,options);observers.push(observer);return observer; }
function watchResize(callback) { const observer=new ResizeObserver(callback);observers.push(observer);return observer; }
`;
  code=code.replace(/export function [^{]+\{\n/,match=>match+setup);
  const clones=name==='mountCategories'?'seamSlides':'seam';
  const timers=name==='mountCategories'?'clearTimeout(resumeTimer);cancelAnimationFrame(updateFrame);':'clearTimeout(timer);';
  return code+`\nreturn () => {destroyed=true;stop();${timers}lifecycle.abort();observers.forEach(o=>o.disconnect());${clones}.forEach(node=>node.remove());};\n}\n`;
}
