const sourceCodes=/\b(?:[345]L(?:AF|A|G[MW]?)?|[2468]U|[1-6]OH|[ACIOUTHS]-LEG|SLAB-LEG|HB|LB|CFP|CFL|CFS-ROD|CFSX?|CFSA|CFA|STF|CFR|LGM|LGW|LWM|MFC|MIX|PN[UMF]?|PNFS|RC[RG]?|SQ|RD|PRF)\b/g;

/** Normalize the known import captions. Product series and editorial titles
 * are kept outside these replacements. */
export function customerModelTitle(title:string,series:string){
 const prefix=title.toLocaleLowerCase('lt').startsWith(series.toLocaleLowerCase('lt'))?title.slice(0,series.length):'';
 let suffix=title.slice(prefix.length);
 suffix=suffix
  .replace(/\b5-STAR\s+(?:su\s+)?apmušalais\b/gi,'su penkiažvaigžde baze ir apmušalais')
  .replace(/\b5-STAR\b/gi,'su penkiažvaigžde baze')
  .replace(/\bUPH(?:\/P)?\b/g,'su apmušalais')
  .replace(/\barmachair\b/gi,'fotelis')
  .replace(/\bhocker\b/gi,'taburetė')
  .replace(/\b(?:with\s+)?electric height adjustment\b/gi,'su elektriniu aukščio reguliavimu')
  .replace(/\b(?:with\s+)?pneumatic height adjustment\b/gi,'su pneumatiniu aukščio reguliavimu')
  .replace(/\b(?:with\s+)?height adjustment by crank\b/gi,'su rankena reguliuojamu aukščiu')
  .replace(/\b(?:with\s+)?fixed height\b/gi,'fiksuoto aukščio')
  .replace(/\b(?:height adjustment\s*[-–]\s*)?ratchet type\b/gi,'su pakopiniu aukščio reguliavimu')
  .replace(/\bmeeting\s*,\s*arrang(?:e)?ment\b/gi,'susitikimų baldų išdėstymas')
  .replace(/\bmeeting(?=\s|,|$)/gi,'susitikimams')
  .replace(/\bworkbench\b/gi,'bendras darbo stalas')
  .replace(/\bbiurko\b/gi,'darbo stalas')
  .replace(/\bwith sideboard\b/gi,'su komoda')
  .replace(/\bwith (?:writing )?tablet\b/gi,'su rašymo lentele')
  .replace(/\bwith two backrests and tablet\b/gi,'su dviem atlošais ir rašymo lentele')
  .replace(/\bwith (two|three) backrests\b/gi,(_,number:string)=>number==='two'?'su dviem atlošais':'su trimis atlošais')
  .replace(/\bwith seat and backrests\b/gi,'su sėdyne ir atlošais')
  .replace(/\bwith drawers\b/gi,'su stalčiais')
  .replace(/\bwith cushions\b/gi,'su pagalvėlėmis')
  .replace(/\bwith seat\b/gi,'su sėdyne')
  .replace(/\bwith (?:height adjustment)\b/gi,'su reguliuojamu aukščiu')
  .replace(/\bwith melamine top\b/gi,'su melamino stalviršiu')
  .replace(/\bwith Fenix top\b/gi,'su „Fenix“ stalviršiu')
  .replace(/\bwith metal top\b/gi,'su metaliniu stalviršiu')
  .replace(/\bwith desktop\b/gi,'su stalviršiu')
  .replace(/\bwith whiteboard\b/gi,'su rašymo lenta')
  .replace(/\bwith flowerpot\b/gi,'su vieta augalams')
  .replace(/\bwith panels\b/gi,'su pertvaromis')
  .replace(/\b(?:set of\s+)?with(?:\s+high|\s+suspended)?\s*$/gi,'')
  .replace(/\bdouble[- ]sided bench\b/gi,'dvipusis suolas')
  .replace(/\bbench\b/gi,'suolas')
  .replace(/\bcoat stand\b/gi,'drabužių kabykla')
  .replace(/\bleg rest\b/gi,'pakojis')
  .replace(/\bchaise longue\b/gi,'šezlongas')
  .replace(/\bmobile panel\b/gi,'mobili pertvara')
  .replace(/\bmobile wall\b/gi,'mobili pertvara')
  .replace(/\bmobile sideboard\b/gi,'mobili komoda')
  .replace(/\bmobile whiteboard\b/gi,'mobili rašymo lenta')
  .replace(/\boffice wall\b/gi,'biuro pertvara')
  .replace(/\breception wall\b/gi,'registratūros pertvara')
  .replace(/\bsuspended panel\b/gi,'pakabinama akustinė plokštė')
  .replace(/\bcorner panel\b/gi,'kampinė plokštė')
  .replace(/\bwall\b/gi,'pertvara')
  .replace(/\bfoldable top\b/gi,'su atlenkiamu stalviršiu')
  .replace(/\bon castors\b/gi,'su ratukais')
  .replace(/\bon four metal legs\b/gi,'su keturiomis metalinėmis kojomis')
  .replace(/\bon 4 wooden legs\b/gi,'su keturiomis medinėmis kojomis')
  .replace(/\bon metal base\b/gi,'su metaliniu pagrindu')
  .replace(/\bon chipboard plinth\b/gi,'su medžio drožlių plokštės cokoliu')
  .replace(/\bwardrobe\b/gi,'drabužių spinta')
  .replace(/\blocker\b/gi,'asmeninių daiktų spintelė')
  .replace(/\btambour[- ]door\b/gi,'spinta su žaliuzinėmis durimis')
  .replace(/\bsliding[- ]door\b/gi,'spinta su stumdomomis durimis')
  .replace(/\bhinged[- ]door\b/gi,'spinta su varstomomis durimis')
  .replace(/\bglass door\b/gi,'spinta su stiklinėmis durimis')
  .replace(/\bdrawer\b/gi,'stalčių spintelė')
  .replace(/\bopen metal\b/gi,'atviras metalinis baldas')
  .replace(/\bopen\b/gi,'atviras variantas')
  .replace(/\bcombi\b/gi,'kombinuotas variantas')
  .replace(/\bsideboard\b/gi,'komoda')
  .replace(/\bwaste box\b/gi,'atliekų dėžė')
  .replace(/\bphone pod\b/gi,'telefoninių pokalbių kabina')
  .replace(/\bfocus pod\b/gi,'individualaus darbo kabina')
  .replace(/\bmeet pod\b/gi,'susitikimų kabina')
  .replace(/\b([A-Z])-shape(?:\s+arrangement)?\b/gi,(_,letter:string)=>letter.toUpperCase()+' formos')
  .replace(/\bflower-shape\b/gi,'gėlės formos')
  .replace(/\bround island\b/gi,'apvali sala')
  .replace(/\bsquare island\b/gi,'kvadratinė sala')
  .replace(/\bround\b/gi,'apvalus variantas')
  .replace(/\bsquare\b/gi,'kvadratinis variantas')
  .replace(/\bset\s+(\d+)\b/gi,'komplektas Nr. $1')
  .replace(/\bset\b/gi,'komplektas')
  .replace(/\barrangement for (\d+) people\b/gi,'išdėstymas $1 asmenims')
  .replace(/\bcorner arrangement\b/gi,'kampinis išdėstymas')
  .replace(/\blinear (?:layout|arrangement)\b/gi,'išdėstymas viena eile')
  .replace(/\blinear\b/gi,'viena eile')
  .replace(/\bdouble[- ]sided\b/gi,'dvipusis variantas')
  .replace(/\bone[- ]sided\b/gi,'vienpusis variantas')
  .replace(/\bswivel\b/gi,'sukamoji kėdė')
  .replace(/\brocking\b/gi,'supamoji kėdė')
  .replace(/\bswing\b/gi,'supamasis variantas')
  .replace(/\bbar\b/gi,'baro kėdė')
  .replace(/\bcounter\b/gi,'kėdė prie aukšto stalo')
  .replace(/\bhigh\b/gi,'aukštas variantas')
  .replace(/\blow\b/gi,'žemas variantas')
  .replace(/\bmobile\b/gi,'mobilus variantas')
  .replace(/\bon X sled metal frame\b/gi,'su X formos metaliniu rėmu')
  .replace(/\bframe\b/gi,'rėmas')
  .replace(/\bpanel\b/gi,'plokštė')
  .replace(/\bmodular\b/gi,'modulinis variantas')
  .replace(/\bveneer\b/gi,'su medienos lukšto apdaila')
  .replace(/\b(?:with\s+)?wood\b/gi,'su medienos elementais')
  .replace(sourceCodes,'')
  .replace(/(?:apmušalais|tinkleliu)(?:\s*\/\s*|\s+)P\b/gi,word=>word.replace(/(?:\s*\/\s*|\s+)P$/i,''))
  .replace(/,\s+(?=su\b)/gi,' ')
  .replace(/\(\s*\)/g,'')
  .replace(/\s+,/g,',')
  .replace(/,\s*,+/g,',')
  .replace(/\s+/g,' ');
 return (prefix+suffix).replace(/^[\s,;/–-]+|[\s,;/–-]+$/g,'')||title;
}
