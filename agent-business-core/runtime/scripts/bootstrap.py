"""Provision the local runtime role without widening account/control privileges."""
import argparse
import asyncio
import os

from sqlalchemy import text
from sqlalchemy.ext.asyncio import create_async_engine

from pinet_core.config import settings
from pinet_core.models import Business, new_id

LEGACY_TABLES = frozenset({
    "businesses", "cases", "mail_messages", "source_checkpoints", "business_policies",
    "policy_revisions", "visitors", "knowledge_states", "case_sources", "conversations",
    "conversation_events", "contacts", "artifacts", "jobs", "outbox", "edge_nonces",
    "admissions", "cost_reservations", "facebook_records", "facebook_account_leases",
})
CONTROL_PRIVILEGES = {
    "control_business_grants": "SELECT", "control_public_projects": "SELECT",
    "control_users": "SELECT,INSERT,UPDATE", "control_sessions": "SELECT,INSERT,UPDATE",
    "control_login_buckets": "SELECT,INSERT,UPDATE",
    "control_customer_accounts": "SELECT,INSERT,UPDATE",
    "control_customer_tokens": "SELECT,INSERT,UPDATE",
    "control_organizations": "SELECT,INSERT", "control_memberships": "SELECT,INSERT",
    "control_portfolios": "SELECT,INSERT", "control_customer_intakes": "SELECT,INSERT",
    "control_task_threads": "SELECT,INSERT,UPDATE", "control_tasks": "SELECT,INSERT,UPDATE",
    "control_task_runs": "SELECT,INSERT,UPDATE", "control_task_events": "SELECT,INSERT",
}


def runtime_password():
    password = os.environ.get("PINET_DB_RUNTIME_PASSWORD")
    if not password:
        from dotenv import dotenv_values
        password = dotenv_values(".env").get("PINET_DB_RUNTIME_PASSWORD")
    if not password or not all(c in "0123456789abcdef" for c in password):
        raise RuntimeError("local runtime password must be generated by setup_local.py")
    return password


async def provision_role(tx, password):
    role = (await tx.execute(text(
        "SELECT rolsuper,rolbypassrls,rolcreatedb,rolcreaterole FROM pg_roles WHERE rolname='pinet_runtime'"
    ))).first()
    if role is None:
        # The sole interpolation is a validated hexadecimal password, never caller SQL.
        if not password or any(c not in "0123456789abcdef" for c in password):
            raise RuntimeError("invalid runtime credential format")
        await tx.execute(text(f"CREATE ROLE pinet_runtime LOGIN PASSWORD '{password}' "
                              "NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE"))
    elif any(role):
        raise RuntimeError("existing runtime role is not restricted")
    # Existing credentials, memberships and role options are never altered.
    await tx.execute(text("GRANT USAGE ON SCHEMA public TO pinet_runtime"))


async def configure_grants(tx):
    tables = set((await tx.execute(text(
        "SELECT tablename FROM pg_tables WHERE schemaname='public'"
    ))).scalars())
    if not LEGACY_TABLES.issubset(tables) or "alembic_version" not in tables:
        raise RuntimeError("complete migrated legacy schema required; use --role-only before migration")
    control = {name for name in tables if name.startswith("control_")}
    version = await tx.scalar(text("SELECT version_num FROM alembic_version"))
    if (control and (control != set(CONTROL_PRIVILEGES) or version != "0012_customer_public")
            or not control and version != "0009_facebook"):
        raise RuntimeError("partial or unsupported control schema; no grants changed")
    if control:
        protected = set((await tx.execute(text(
            "SELECT relname FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace "
            "WHERE n.nspname='public' AND c.relrowsecurity AND c.relforcerowsecurity"
        ))).scalars())
        if not control.issubset(protected):
            raise RuntimeError("all control tables require forced RLS")
    # Only maintained exact tables receive grants. Future/foreign tables are untouched.
    grants = {name: "SELECT,INSERT,UPDATE,DELETE" for name in LEGACY_TABLES}
    grants["businesses"] = "SELECT"
    grants.update(CONTROL_PRIVILEGES if control else {})
    for name, privileges in sorted(grants.items()):
        await tx.execute(text(f"REVOKE ALL ON public.{name} FROM pinet_runtime"))
        await tx.execute(text(f"GRANT {privileges} ON public.{name} TO pinet_runtime"))
    await tx.execute(text("REVOKE ALL ON public.alembic_version FROM pinet_runtime"))
    # Fail closed if inherited/PUBLIC grants would still bypass the exact matrix.
    for name in sorted(control):
        for privilege in ("SELECT", "INSERT", "UPDATE", "DELETE", "TRUNCATE", "REFERENCES", "TRIGGER"):
            effective = await tx.scalar(text("SELECT has_table_privilege('pinet_runtime', :t, :p)"),
                                        {"t": "public." + name, "p": privilege})
            if effective != (privilege in CONTROL_PRIVILEGES[name].split(",")):
                raise RuntimeError("runtime control privileges differ from maintained grant matrix")


async def bootstrap(tx, *, password, role_only=False):
    await provision_role(tx, password)
    if role_only:
        return
    await configure_grants(tx)
    for site, host in [("traktoriupadangos", "traktoriupadangos.lt"),
                       ("greitossvetaines", "greitossvetaines.lt")]:
        if not await tx.scalar(text("SELECT id FROM businesses WHERE site_id=:s"), {"s": site}):
            await tx.execute(Business.__table__.insert().values(id=new_id(), site_id=site, canonical_host=host))


async def main(*, role_only=False):
    engine = create_async_engine(settings().admin_database_url)
    try:
        async with engine.begin() as tx:
            await bootstrap(tx, password=runtime_password(), role_only=role_only)
    finally:
        await engine.dispose()
    print("Restricted runtime role ready." if role_only else
          "Exact runtime privileges and stable site mappings ready; no customer data seeded.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--role-only", action="store_true", help="Provision role before immutable migrations")
    asyncio.run(main(role_only=parser.parse_args().role_only))
