"""Local runtime role; migration owner and application role stay distinct."""
import argparse
import asyncio
import os

from sqlalchemy import text
from sqlalchemy.ext.asyncio import create_async_engine

from pinet_core.acquisition.ledger_schema import TABLES as ACQUISITION_TABLES
from pinet_core.acquisition.ledger_schema import runtime_grants_sql
from pinet_core.acquisition.module_schema import TABLE as ACQUISITION_MODULE_TABLE
from pinet_core.acquisition.module_schema import grants_sql as acquisition_module_grants_sql
from pinet_core.acquisition.work_schema import TABLES as ACQUISITION_WORK_TABLES
from pinet_core.acquisition.work_schema import runtime_grants_sql as acquisition_work_grants_sql
from pinet_core.config import settings
from pinet_core.models import Business, new_id


async def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--role-only", action="store_true", help="Provision restricted role before fresh migrations.")
    args = parser.parse_args()
    cfg = settings()
    engine = create_async_engine(cfg.admin_database_url)
    password = os.environ.get("PINET_DB_RUNTIME_PASSWORD")
    if not password:
        from dotenv import dotenv_values
        password = dotenv_values(".env").get("PINET_DB_RUNTIME_PASSWORD")
    if not password or not all(c in "0123456789abcdef" for c in password):
        raise RuntimeError("local runtime password must be generated by setup_local.py")
    async with engine.begin() as tx:
        exists = await tx.scalar(text("SELECT 1 FROM pg_roles WHERE rolname='pinet_runtime'"))
        if not exists:
            await tx.execute(text(f"CREATE ROLE pinet_runtime LOGIN PASSWORD '{password}' "
                                  "NOSUPERUSER NOBYPASSRLS NOCREATEDB NOCREATEROLE"))
        await tx.execute(text("GRANT USAGE ON SCHEMA public TO pinet_runtime"))
        if not args.role_only:
            # Repair prior broadening, rather than merely excluding future grants.
            known = set(await tx.scalars(text("SELECT tablename FROM pg_tables WHERE schemaname='public'")))
            acquisition = known.intersection(ACQUISITION_TABLES)
            work = known.intersection(ACQUISITION_WORK_TABLES)
            if work and (work != set(ACQUISITION_WORK_TABLES) or acquisition != set(ACQUISITION_TABLES)
                         or ACQUISITION_MODULE_TABLE not in known):
                raise RuntimeError("Partial acquisition work schema; bootstrap grants refused")
            if acquisition and acquisition != set(ACQUISITION_TABLES):
                raise RuntimeError("Partial acquisition schema; bootstrap grants refused")
            if acquisition:
                for statement in runtime_grants_sql():
                    await tx.execute(text(statement))
            if ACQUISITION_MODULE_TABLE in known:
                if acquisition != set(ACQUISITION_TABLES):
                    raise RuntimeError("Partial acquisition schema; bootstrap grants refused")
                for statement in acquisition_module_grants_sql():
                    await tx.execute(text(statement))
            if work:
                for statement in acquisition_work_grants_sql():
                    await tx.execute(text(statement))
            # Module-owned tables retain their least-privilege migration grants.
            tables = (await tx.execute(text("SELECT tablename FROM pg_tables WHERE schemaname='public' "
                                           "AND tablename NOT LIKE 'control_%' AND tablename NOT LIKE 'acquisition_%'"))).scalars()
            for table in tables:
                quoted = engine.dialect.identifier_preparer.quote(table)
                await tx.execute(text(f"GRANT SELECT,INSERT,UPDATE,DELETE ON {quoted} TO pinet_runtime"))
            await tx.execute(text("REVOKE ALL ON alembic_version FROM pinet_runtime"))
            await tx.execute(text("REVOKE INSERT, UPDATE, DELETE ON businesses FROM pinet_runtime"))
            for site, host in [("traktoriupadangos", "traktoriupadangos.lt"),
                               ("greitossvetaines", "greitossvetaines.lt")]:
                if not await tx.scalar(text("SELECT id FROM businesses WHERE site_id=:s"), {"s": site}):
                    await tx.execute(Business.__table__.insert().values(id=new_id(), site_id=site, canonical_host=host))
    await engine.dispose()
    print("Restricted role ready." if args.role_only else "Runtime role and stable site mappings ready; no customer data seeded.")


asyncio.run(main())
